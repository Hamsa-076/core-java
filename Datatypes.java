public class Datatypes { //data types
    public static void main(String[] args) {
        byte b = 12; //byte
        float f = 1.3f; //float
        int num = 12; //number
        long L = 79765678L; //long
        short s = 32767; //short
        boolean bool = false; //true or false
        double d = 1.2; //double
        char c = 'A'; //char
        System.out.println(b+" "+num+" "+f+" "+L+" "+bool+" "+s+" "+c+" "+d);
    }
}
